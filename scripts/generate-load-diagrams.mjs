/**
 * generate-load-diagrams.mjs — draw the load size scale as exact SVG diagrams.
 *
 * ─────────────────────── Why this is not photography ───────────────────────
 *
 * The load scale was attempted three times as generated photography and failed
 * each time. The failure is structural, not a prompting mistake:
 *
 *   1. With the tow vehicle in frame, the truck dominated, the trailer was small
 *      and clipped, fill levels were unreadable, and the model swapped in a
 *      different truck with visible brand badges on every run.
 *   2. Trailer-only at low derivation strength held the trailer perfectly but
 *      rendered an empty deck every time, ignoring the load.
 *   3. Trailer-only at high strength finally showed readable, progressive fill
 *      levels, but by then the vehicle itself had changed between frames: two of
 *      the six turned into flatbed trucks.
 *
 * The tension is inherent. Enough pixel change to show a load is enough pixel
 * change to replace the vehicle. A measuring instrument has to be identical in
 * every frame or it is not measuring anything.
 *
 * A diagram is the better answer on every axis that matters here. Fill levels are
 * mathematically exact rather than approximate, the trailer is identical by
 * construction, it stays crisp at any size, it costs about 1 KB instead of
 * 400 KB, and it is honestly a diagram rather than a photograph implying we
 * photographed this exact load.
 *
 * The fractions come from src/data/pricing.ts, so the drawing and the data can
 * never disagree.
 *
 * Usage: node scripts/generate-load-diagrams.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, resolve, join } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const OUT = resolve(root, 'src/assets/diagrams');

/** Kept in step with src/data/pricing.ts. */
const LOADS = [
  { slug: 'load-single-item', name: 'Single item', fraction: 0.08 },
  { slug: 'load-small', name: 'Small load', fraction: 0.15 },
  { slug: 'load-quarter', name: 'Quarter load', fraction: 0.25 },
  { slug: 'load-half', name: 'Half load', fraction: 0.5 },
  { slug: 'load-three-quarter', name: 'Three-quarter load', fraction: 0.75 },
  { slug: 'load-full', name: 'Full load', fraction: 1 },
];

/* Palette from DESIGN.md. */
const SPRUCE = '#123329';
const HI_VIS = '#CFE034';
const RULE = '#D8D3C8';
const INK_3 = '#878D87';

/* Geometry, in viewBox units. Side elevation of an open utility trailer. */
const W = 300;
const H = 180;
const DECK_Y = 118; // top surface of the deck
const DECK_X = 24;
const DECK_W = 252;
const RAIL_H = 46; // mesh side rail height above the deck
const RAIL_Y = DECK_Y - RAIL_H;

/**
 * Load geometry, drawn to preserve AREA rather than height.
 *
 * A sofa on an empty trailer is a lump at one end, not a thin sheet spread over
 * the whole deck, so drawing small loads as full-width layers looks wrong and
 * reads as "barely anything" rather than "one big item". Instead the drawn
 * rectangle always has an area of exactly `fraction` of the deck area, but small
 * loads are drawn tall and narrow so they look like objects sitting on the deck.
 *
 * The scale therefore stays mathematically honest at every step while looking
 * like what it represents.
 */
const DECK_AREA_W = DECK_W - 12;

function loadRect(fraction) {
  const area = fraction * DECK_AREA_W * RAIL_H;

  // Larger loads spread across the full deck and stack upwards.
  if (fraction >= 0.25) {
    const h = area / DECK_AREA_W;
    const heap = fraction >= 0.95 ? 10 : 0;
    return { x: DECK_X + 6, w: DECK_AREA_W, h: h + heap, y: DECK_Y - h - heap };
  }

  // Small loads sit as a concentrated pile at the front of the deck.
  const h = Math.min(RAIL_H * 0.62, Math.sqrt(area * 1.6));
  const w = area / h;
  return { x: DECK_X + 18, w, h, y: DECK_Y - h };
}

const meshPattern = (id) => `
    <pattern id="${id}" width="8" height="8" patternUnits="userSpaceOnUse">
      <path d="M0 0 L8 8 M8 0 L0 8" stroke="${INK_3}" stroke-width="0.7" opacity="0.55" />
    </pattern>`;

function diagram({ slug, name, fraction }) {
  const load = loadRect(fraction);

  return `<?xml version="1.0" encoding="UTF-8"?>
<!--
  ${slug}.svg — ${name} (${Math.round(fraction * 100)}% of one trailer load).

  Generated by scripts/generate-load-diagrams.mjs from the fractions in
  src/data/pricing.ts. Do not hand-edit: rerun the script instead.

  Side elevation of the open utility trailer. The drawn load area is exactly
  ${Math.round(fraction * 100)}% of the deck area, so the six diagrams form a real
  scale rather than an impression of one.
-->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${W} ${H}" width="${W}" height="${H}"
     role="img" aria-label="${name}, about ${Math.round(fraction * 100)} percent of a full trailer load">
  <defs>${meshPattern(`mesh-${slug}`)}</defs>

  <!-- load, area-proportional -->
  <rect x="${load.x.toFixed(1)}" y="${load.y.toFixed(1)}" width="${load.w.toFixed(1)}" height="${load.h.toFixed(1)}" fill="${HI_VIS}" />

  <!-- mesh side rail, drawn over the load so the load sits inside the trailer -->
  <rect x="${DECK_X}" y="${RAIL_Y}" width="${DECK_W}" height="${RAIL_H}" fill="url(#mesh-${slug})" />
  <rect x="${DECK_X}" y="${RAIL_Y}" width="${DECK_W}" height="${RAIL_H}" fill="none"
        stroke="${SPRUCE}" stroke-width="3" />

  <!-- front and rear uprights -->
  <rect x="${DECK_X - 3}" y="${RAIL_Y - 8}" width="6" height="${RAIL_H + 8}" fill="${SPRUCE}" />
  <rect x="${DECK_X + DECK_W - 3}" y="${RAIL_Y - 8}" width="6" height="${RAIL_H + 8}" fill="${SPRUCE}" />

  <!-- deck and frame -->
  <rect x="${DECK_X}" y="${DECK_Y}" width="${DECK_W}" height="10" fill="${SPRUCE}" />

  <!-- tongue and coupler -->
  <path d="M${DECK_X} ${DECK_Y + 5} L${DECK_X - 20} ${DECK_Y + 5}" stroke="${SPRUCE}" stroke-width="5" />
  <rect x="${DECK_X - 24}" y="${DECK_Y}" width="8" height="10" fill="${SPRUCE}" />

  <!-- wheels -->
  <circle cx="${DECK_X + 78}" cy="${DECK_Y + 26}" r="16" fill="${SPRUCE}" />
  <circle cx="${DECK_X + 78}" cy="${DECK_Y + 26}" r="6" fill="${RULE}" />
  <circle cx="${DECK_X + 118}" cy="${DECK_Y + 26}" r="16" fill="${SPRUCE}" />
  <circle cx="${DECK_X + 118}" cy="${DECK_Y + 26}" r="6" fill="${RULE}" />

  <!-- ground line -->
  <path d="M0 ${DECK_Y + 43} L${W} ${DECK_Y + 43}" stroke="${RULE}" stroke-width="2" />
</svg>
`;
}

await mkdir(OUT, { recursive: true });
for (const load of LOADS) {
  await writeFile(join(OUT, `${load.slug}.svg`), diagram(load));
  console.log(`[loads] ${load.slug}.svg  ${Math.round(load.fraction * 100)}%`);
}
console.log(`[loads] Wrote ${LOADS.length} diagrams to src/assets/diagrams/`);
